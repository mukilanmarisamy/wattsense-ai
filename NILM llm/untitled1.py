import numpy as np
import pandas as pd
import tensorflow as tf
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Conv1D, Flatten, Dense, Dropout, Input
from tensorflow.keras.callbacks import ModelCheckpoint
import os

# 1. Load the generated dataset
print("Loading data...")
df = pd.read_csv("train_data_ac.csv")
aggregate = df['aggregate'].values
appliance = df['appliance'].values

# 2. Prepare the Sliding Windows
# Seq2Point expects a window of the total power to predict the appliance power at the midpoint
WINDOW_SIZE = 599  # Standard window size for 1-minute to low-frequency data
half_window = WINDOW_SIZE // 2

print(f"Structuring data into sliding windows of size {WINDOW_SIZE}...")
# Pad the aggregate array with zeros to handle boundaries
padded_aggregate = np.pad(aggregate, half_window, mode='constant', constant_values=0)

X = []
y = []

# Populate the sliding windows
for i in range(len(aggregate)):
    window = padded_aggregate[i : i + WINDOW_SIZE]
    X.append(window)
    y.append(appliance[i])

X = np.array(X)
y = np.array(y)

# Reshape X to fit the Conv1D input requirement: (samples, window_size, 1)
X = np.reshape(X, (X.shape[0], X.shape[1], 1))

print(f"Data shape prepared for training: X={X.shape}, y={y.shape}")

# 3. Build the Standard Seq2Point Neural Network Architecture
model = Sequential([
    Input(shape=(WINDOW_SIZE, 1)),
    Conv1D(filters=30, kernel_size=10, strides=1, activation='relu', padding='same'),
    Conv1D(filters=30, kernel_size=8, strides=1, activation='relu', padding='same'),
    Conv1D(filters=40, kernel_size=6, strides=1, activation='relu', padding='same'),
    Conv1D(filters=50, kernel_size=5, strides=1, activation='relu', padding='same'),
    Conv1D(filters=50, kernel_size=5, strides=1, activation='relu', padding='same'),
    Flatten(),
    Dense(1024, activation='relu'),
    Dropout(0.5),
    Dense(1, activation='linear')  # Continuous wattage output
])

model.compile(optimizer='adam', loss='mse', metrics=['mae'])
model.summary()

# 4. Create directories & train the model
if not os.path.exists("./saved_models"):
    os.makedirs("./saved_models")

checkpoint = ModelCheckpoint('./saved_models/seq2point_ac1.keras', save_best_only=True, monitor='loss', mode='min')

print("\nStarting Training...")
history = model.fit(
    X, y,
    epochs=5,
    batch_size=32,
    callbacks=[checkpoint],
    verbose=1
)

print("\n[Success] Training complete! Model saved to ./saved_models/seq2point_ac1.keras")

